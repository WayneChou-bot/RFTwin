const DICT: Record<Lang, Record<TKey, string>> = { en, zh };

function detect(): Lang {
  try {
    const s = localStorage.getItem(KEY);
    if (s === "zh" || s === "en") return s;
  } catch { /* storage unavailable */ }
  const n = (typeof navigator !== "undefined" && navigator.language) || "";
  return /^zh/i.test(n) ? "zh" : "en";
}

function applyHtmlLang(l: Lang) {
  if (typeof document !== "undefined") document.documentElement.lang = l === "zh" ? "zh-Hant" : "en";
}

export const useLang = create<{ lang: Lang; setLang: (l: Lang) => void }>((set) => ({
  lang: detect(),
  setLang: (l) => {
    try { localStorage.setItem(KEY, l); } catch { /* ignore */ }
    applyHtmlLang(l);
    set({ lang: l });
  },
}));
applyHtmlLang(useLang.getState().lang);

export type Vars = Record<string, string | number>;
/** §56（Review）：要「存起來稍後顯示」的訊息存鍵＋變數，不存翻好的字串——語言切換時才會跟著換。 */
export type Msg = { key: TKey; vars?: Vars; labelKey?: TKey } | null;   // labelKey：訊息內的操作名稱也走字典

export function tr(lang: Lang, key: TKey, vars?: Vars): string {
  let s: string = DICT[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** 非元件函式用（事件處理、規則式文字）；讀當前語言。 */
export function t(key: TKey, vars?: Vars): string {
  return tr(useLang.getState().lang, key, vars);
}

/** 元件用：語言切換時重繪。 */
export function useT() {
  const lang = useLang((s) => s.lang);
  return useCallback((key: TKey, vars?: Vars) => tr(lang, key, vars), [lang]);
}

/** Cell／區域名稱：依 id 翻譯，沒有對應就用引擎給的名字。 */
export function cellName(lang: Lang, cellId: string | null | undefined, fallback: string): string {
  return cellId ? tOpt(lang, `cell.${cellId}`, fallback) : fallback;
}

/** 有對應鍵就翻譯，否則原字（動態 id → 鍵）。 */
export function tOpt(lang: Lang, key: string, fallback: string): string {
  return key in DICT[lang] ? DICT[lang][key as TKey] : fallback;
}
